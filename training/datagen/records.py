"""
Synthetic product-label RECORD generator (text level).

A record describes one fictional packaged product:
  * `fields`        - canonical ground-truth values (what an ideal extractor should return)
  * `panels`        - the text lines printed on the front / back panel, each tagged with the
                      field(s) it declares, a size class and style hints for the renderer
  * `defects`       - deliberately injected Legal Metrology labelling problems (for compliance tests)
  * `split`         - train / val / test, decided by BRAND so the same brand never appears in two splits

Every record is generated from `random.Random(f"{seed}:{index}")`, so the dataset is exactly
reproducible and can be generated in parallel.
"""
from __future__ import annotations

import hashlib
import random
import re
from dataclasses import dataclass

