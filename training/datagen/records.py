        mname = f"{rng.choice(['Oleo', 'Vita', 'Nordic', 'Euro', 'Pacific', 'Atlas', 'Siam', 'Hanil', 'Lumen'])} " \
                f"{rng.choice(['Foods', 'Cosmetics', 'Industries', 'Trading', 'Manufacturing'])} " \
                f"{rng.choice(['S.L.', 'S.p.A.', 'Co., Ltd.', 'GmbH', 'Sdn. Bhd.', 'Inc.'])}"
